namespace Apperture.Core.Application.Accounts;

/// <summary>
/// Hard limits for the avatar upload pipeline. These are platform constants rather than settings:
/// relaxing them is a security decision, not an operator preference.
/// </summary>
public static class ProfileImageLimits
{
    /// <summary>Largest accepted upload body. Anything larger is rejected before decoding.</summary>
    public const int MaxUploadBytes = 4 * 1024 * 1024;

    /// <summary>Largest accepted source dimension, guarding against decompression-bomb inputs.</summary>
    public const int MaxSourceDimension = 8_000;

    /// <summary>Largest accepted total source pixel count (width × height).</summary>
    public const int MaxSourcePixels = 40_000_000;

    /// <summary>Smallest useful source dimension.</summary>
    public const int MinSourceDimension = 16;

    /// <summary>Square edge lengths generated for every stored avatar, largest first.</summary>
    public static IReadOnlyList<int> RenditionSizes { get; } = [256, 128, 64];

    /// <summary>Content type of every stored rendition. Uploads are always re-encoded to this.</summary>
    public const string OutputContentType = "image/png";

    public static bool IsSupportedRenditionSize(int size) => RenditionSizes.Contains(size);

    /// <summary>
    /// Media types the API will even attempt to decode. The declared type is a cheap pre-filter only;
    /// the decoder still determines what the bytes actually are.
    /// </summary>
    public static IReadOnlyList<string> AcceptedUploadContentTypes { get; } =
        ["image/jpeg", "image/png", "image/webp"];

    public static IReadOnlyList<string> AcceptedUploadExtensions { get; } =
        [".jpg", ".jpeg", ".png", ".webp"];

    public static bool IsAcceptedUploadContentType(string? contentType)
    {
        if (string.IsNullOrWhiteSpace(contentType))
            return false;
        var value = contentType.Split(';')[0].Trim();
        return AcceptedUploadContentTypes.Contains(value, StringComparer.OrdinalIgnoreCase);
    }

    public static bool IsAcceptedUploadExtension(string? fileName)
    {
        if (string.IsNullOrWhiteSpace(fileName))
            return false;
        var extension = Path.GetExtension(fileName);
        return !string.IsNullOrEmpty(extension)
            && AcceptedUploadExtensions.Contains(extension, StringComparer.OrdinalIgnoreCase);
    }
}

/// <summary>Why an upload was refused. Stable codes so the UI can render specific guidance.</summary>
public enum ProfileImageRejectionReason
{
    None = 0,
    Empty,
    TooLarge,
    UnsupportedDeclaredType,
    UndecodableImage,
    UnsupportedImageFormat,
    DimensionsTooLarge,
    DimensionsTooSmall,
    EncodeFailed
}

/// <summary>A single square, re-encoded avatar image ready to be stored.</summary>
public sealed record ProfileImageRendition(int Size, string ContentType, byte[] Content);

/// <summary>Outcome of normalizing an untrusted upload.</summary>
public sealed record ProfileImageNormalizationResult(
    bool Succeeded,
    ProfileImageRejectionReason Reason,
    string? Message,
    IReadOnlyList<ProfileImageRendition> Renditions,
    int SourceWidth,
    int SourceHeight,
    string? SourceFormat)
{
    public static ProfileImageNormalizationResult Rejected(ProfileImageRejectionReason reason, string message) =>
        new(false, reason, message, [], 0, 0, null);

    public static ProfileImageNormalizationResult Success(
        IReadOnlyList<ProfileImageRendition> renditions,
        int sourceWidth,
        int sourceHeight,
        string? sourceFormat) =>
        new(true, ProfileImageRejectionReason.None, null, renditions, sourceWidth, sourceHeight, sourceFormat);
}

/// <summary>
/// Decodes untrusted image bytes and produces platform-controlled square renditions.
/// Implementations must never trust the declared content type, must not retain source metadata,
/// and must not write anything to disk.
/// </summary>
public interface IProfileImageNormalizer
{
    ProfileImageNormalizationResult Normalize(ReadOnlySpan<byte> content);
}

/// <summary>A stored avatar rendition retrieved for serving.</summary>
public sealed record ProfileImageContent(string ContentType, byte[] Content);

/// <summary>
/// Storage for normalized avatar renditions. The key is generated by the platform; callers never
/// supply a path, and no environment-specific location is persisted on the user record.
/// </summary>
public interface IUserProfileImageStore
{
    /// <summary>Persists all renditions for a newly generated image key.</summary>
    ValueTask SaveAsync(
        string userId,
        string imageKey,
        IReadOnlyList<ProfileImageRendition> renditions,
        CancellationToken cancellationToken = default);

    /// <summary>
    /// Reads one rendition. Scoped by user id so a leaked key cannot be read from another account.
    /// </summary>
    ValueTask<ProfileImageContent?> GetAsync(
        string userId,
        string imageKey,
        int size,
        CancellationToken cancellationToken = default);

    /// <summary>
    /// Deletes every rendition a user owns except <paramref name="keepImageKey"/>. Passing null
    /// removes all of them. Returns the number of image keys retired.
    /// </summary>
    ValueTask<int> DeleteForUserAsync(
        string userId,
        string? keepImageKey,
        CancellationToken cancellationToken = default);
}
