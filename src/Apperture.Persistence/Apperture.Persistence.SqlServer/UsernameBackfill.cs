using System.Data;
using System.Data.Common;
using System.Text.RegularExpressions;
using Apperture.Core.Application.Services;
using Microsoft.Data.SqlClient;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging;

namespace Apperture.Persistence.SqlServer;

/// <summary>
/// The data step between <c>Iam9_UsernameLedger</c> and <c>Iam9_UsernameRequired</c>: gives every user a
/// username and records it in the username ledger.
/// </summary>
/// <remarks>
/// <para>Order is fixed and deterministic:</para>
/// <list type="number">
/// <item>Users with a Local link keep their sign-in name verbatim (trimmed, lower-cased), even when it does
/// not satisfy the current username policy. This covers mixed Local and Entra users, Recovery Access, and
/// Local bootstrap and development users.</item>
/// <item>Earlier Recovery Access usernames recorded by the canonicalization audit are added to the ledger
/// as retired names of the same user, only when the mapping is unambiguous and the name is free.</item>
/// <item>Users still without a username (Entra-only, or with no links) get a generated name.</item>
/// </list>
/// <para>Within each group, users are ordered by their earliest identity link, then by id. Every user is
/// written in its own transaction and every write re-checks the current state, so the step is idempotent
/// and safe to re-run after an interrupted start. Database constraints, not this code, decide whether a
/// name is free. Schema access is plain SQL against the shape created by <c>Iam9_UsernameLedger</c>, so the
/// step does not depend on the current EF model.</para>
/// </remarks>
public static partial class UsernameBackfill
{
    /// <summary>Audit action for a username generated by this step (actor <c>system</c>).</summary>
    public const string AssignedAuditAction = "identity.username.assigned";

    /// <summary>
    /// Must equal <c>EmergencyAccessAuditActionNames.Canonicalized</c>, which this assembly cannot
    /// reference. A unit test pins the two together.
    /// </summary>
    public const string RecoveryAccessCanonicalizedAuditAction = "emergency.access.canonicalized";

    private const string SystemActor = "system";
    private const string AuditOutcome = "auth-admin";
    private const string BootstrapDisplayNamePrefix = "Bootstrap administrator (";
    private const int LocalSource = 1;
    private const int EntraSource = 0;

    public static async Task<UsernameBackfillReport> RunAsync(
        AppertureDbContext db,
        ILogger logger,
        CancellationToken cancellationToken = default,
        Func<string>? randomSuffix = null)
    {
        var connection = (SqlConnection)db.Database.GetDbConnection();
        var openedHere = connection.State != ConnectionState.Open;
        if (openedHere)
            await connection.OpenAsync(cancellationToken).ConfigureAwait(false);

        try
        {
            var report = new UsernameBackfillReport();
            await BackfillLocalUsersAsync(connection, report, logger, cancellationToken).ConfigureAwait(false);
            await RecordPreviousRecoveryAccessNamesAsync(connection, report, logger, cancellationToken).ConfigureAwait(false);
            await GenerateRemainingUsernamesAsync(connection, report, logger, randomSuffix, cancellationToken).ConfigureAwait(false);

            logger.LogInformation(
                "Username backfill complete. LocalPreserved={LocalPreserved}, LocalGrandfathered={LocalGrandfathered}, Generated={Generated}, GeneratedWithSuffix={GeneratedWithSuffix}, ReservedNameHolders={ReservedNameHolders}, PreviousRecoveryAccessNamesRecorded={PreviousRecorded}, PreviousRecoveryAccessNamesSkipped={PreviousSkipped}",
                report.LocalPreserved,
                report.LocalGrandfathered,
                report.Generated,
                report.GeneratedWithSuffix,
                report.ReservedNameHolders,
                report.PreviousRecoveryAccessNamesRecorded,
                report.PreviousRecoveryAccessNamesSkipped);
            return report;
        }
        finally
        {
            if (openedHere)
                await connection.CloseAsync().ConfigureAwait(false);
        }
    }

    // ---------------------------------------------------------------------------------------------
    // 1. Local users: the sign-in name is the username, verbatim.
    // ---------------------------------------------------------------------------------------------

    private static async Task BackfillLocalUsersAsync(
        SqlConnection connection,
        UsernameBackfillReport report,
        ILogger logger,
        CancellationToken cancellationToken)
    {
        var rows = new List<(string UserId, string LinkId, string ExternalId, DateTimeOffset LinkedAt, bool IsRecoveryAccess)>();
        await using (var command = Command(connection, null, """
            SELECT u.[Id], il.[Id], il.[ExternalId], il.[LinkedAt], u.[IsBreakGlassEligible]
            FROM Users u
            INNER JOIN IdentityLinks il ON il.[UserId] = u.[Id] AND il.[Source] = @local
            WHERE u.[Username] IS NULL
            ORDER BY (SELECT MIN(x.[LinkedAt]) FROM IdentityLinks x WHERE x.[UserId] = u.[Id]), u.[Id];
            """, ("@local", LocalSource)))
        await using (var reader = await command.ExecuteReaderAsync(cancellationToken).ConfigureAwait(false))
        {
            while (await reader.ReadAsync(cancellationToken).ConfigureAwait(false))
            {
                rows.Add((reader.GetString(0), reader.GetString(1), reader.GetString(2), reader.GetFieldValue<DateTimeOffset>(3), reader.GetBoolean(4)));
            }
        }

        foreach (var row in rows)
        {
            var username = UsernamePolicy.Normalize(row.ExternalId);
            if (username.Length == 0)
            {
                throw new InvalidOperationException(
                    $"User {row.UserId} has a Local identity link with an empty sign-in name. Fix or remove that link, then start the Management Host again.");
            }

            await using var transaction = (SqlTransaction)await connection.BeginTransactionAsync(cancellationToken).ConfigureAwait(false);

            var owner = await LedgerOwnerAsync(connection, transaction, username, cancellationToken).ConfigureAwait(false);
            if (owner is null)
            {
                await ExecuteAsync(connection, transaction, """
                    INSERT INTO UsernameLedger ([Username], [UserId], [AssignedAtUtc], [RetiredAtUtc], [RetiredReason])
                    VALUES (@username, @userId, @assignedAt, NULL, NULL);
                    """, cancellationToken, ("@username", username), ("@userId", row.UserId), ("@assignedAt", row.LinkedAt)).ConfigureAwait(false);
            }
            else if (!string.Equals(owner.Value.UserId, row.UserId, StringComparison.Ordinal))
            {
                throw new InvalidOperationException(
                    $"Cannot assign usernames: the Local sign-in name '{username}' of user {row.UserId} is already the username of user {owner.Value.UserId}. " +
                    "Two Local sign-in names differ only by case or surrounding spaces. Rename or remove one of them, then start the Management Host again.");
            }
            else if (!owner.Value.IsCurrent)
            {
                await ExecuteAsync(connection, transaction, """
                    UPDATE UsernameLedger SET [RetiredAtUtc] = NULL, [RetiredReason] = NULL
                    WHERE [Username] = @username AND [UserId] = @userId;
                    """, cancellationToken, ("@username", username), ("@userId", row.UserId)).ConfigureAwait(false);
            }

            var updated = await ExecuteAsync(connection, transaction, """
                UPDATE Users SET [Username] = @username WHERE [Id] = @userId AND [Username] IS NULL;
                """, cancellationToken, ("@username", username), ("@userId", row.UserId)).ConfigureAwait(false);
            if (updated == 0)
            {
                // Another start completed this user first.
                await transaction.RollbackAsync(cancellationToken).ConfigureAwait(false);
                continue;
            }

            if (!string.Equals(row.ExternalId, username, StringComparison.Ordinal))
            {
                // Sign-in already normalizes input, so lower-casing the stored link changes nothing for the user.
                try
                {
                    await ExecuteAsync(connection, transaction, """
                        UPDATE IdentityLinks SET [ExternalId] = @username WHERE [Id] = @linkId;
                        """, cancellationToken, ("@username", username), ("@linkId", row.LinkId)).ConfigureAwait(false);
                }
                catch (SqlException ex) when (ex.Number is 2601 or 2627)
                {
                    throw new InvalidOperationException(
                        $"Cannot assign usernames: normalizing the Local sign-in name of user {row.UserId} to '{username}' collides with another Local identity link. " +
                        "Rename or remove one of them, then start the Management Host again.",
                        ex);
                }
            }

            await transaction.CommitAsync(cancellationToken).ConfigureAwait(false);

            report.LocalPreserved++;
            if (!UsernamePolicy.IsValidFormat(username))
            {
                report.LocalGrandfathered++;
                logger.LogInformation(
                    "Kept Local username {Username} for user {UserId} verbatim although it does not satisfy the current username policy.",
                    username,
                    row.UserId);
            }
            else if (UsernamePolicy.IsReserved(username)
                     && !(row.IsRecoveryAccess && username == UsernamePolicy.RecoveryAccessUsername))
            {
                report.ReservedNameHolders++;
                logger.LogWarning(
                    "User {UserId} keeps the reserved username {Username}. New assignments of this name are refused.",
                    row.UserId,
                    username);
            }
        }
    }

    // ---------------------------------------------------------------------------------------------
    // 2. Previous Recovery Access names from the canonicalization audit.
    // ---------------------------------------------------------------------------------------------

    private static async Task RecordPreviousRecoveryAccessNamesAsync(
        SqlConnection connection,
        UsernameBackfillReport report,
        ILogger logger,
        CancellationToken cancellationToken)
    {
        var owners = new SortedDictionary<string, (HashSet<string> UserIds, DateTimeOffset FirstAt)>(StringComparer.Ordinal);
        await using (var command = Command(connection, null, """
            SELECT [At], [Details] FROM AuditLogs WHERE [Action] = @action ORDER BY [Id];
            """, ("@action", RecoveryAccessCanonicalizedAuditAction)))
        await using (var reader = await command.ExecuteReaderAsync(cancellationToken).ConfigureAwait(false))
        {
            while (await reader.ReadAsync(cancellationToken).ConfigureAwait(false))
            {
                if (reader.IsDBNull(1) || !TryParseCanonicalization(reader.GetString(1), out var userId, out var previous))
                    continue;
                if (previous == UsernamePolicy.RecoveryAccessUsername)
                    continue;

                var at = reader.GetFieldValue<DateTimeOffset>(0);
                if (owners.TryGetValue(previous, out var existing))
                {
                    existing.UserIds.Add(userId);
                    owners[previous] = (existing.UserIds, existing.FirstAt <= at ? existing.FirstAt : at);
                }
                else
                {
                    owners[previous] = (new HashSet<string>(StringComparer.Ordinal) { userId }, at);
                }
            }
        }

        foreach (var (previous, entry) in owners)
        {
            if (entry.UserIds.Count != 1)
            {
                report.PreviousRecoveryAccessNamesSkipped++;
                logger.LogWarning(
                    "Previous Recovery Access username {Username} is recorded for more than one user; it was not added to the username ledger.",
                    previous);
                continue;
            }

            var userId = entry.UserIds.Single();
            if (await ScalarAsync(connection, null, "SELECT COUNT(*) FROM Users WHERE [Id] = @userId;", cancellationToken, ("@userId", userId)).ConfigureAwait(false) == 0)
            {
                report.PreviousRecoveryAccessNamesSkipped++;
                logger.LogWarning(
                    "Previous Recovery Access username {Username} belongs to user {UserId}, which no longer exists; it was not added to the username ledger.",
                    previous,
                    userId);
                continue;
            }

            var owner = await LedgerOwnerAsync(connection, null, previous, cancellationToken).ConfigureAwait(false);
            if (owner is not null)
            {
                if (!string.Equals(owner.Value.UserId, userId, StringComparison.Ordinal))
                {
                    report.PreviousRecoveryAccessNamesSkipped++;
                    logger.LogWarning(
                        "Previous Recovery Access username {Username} of user {UserId} is held by user {OwnerUserId}; current ownership was kept.",
                        previous,
                        userId,
                        owner.Value.UserId);
                }

                continue;
            }

            try
            {
                await ExecuteAsync(connection, null, """
                    INSERT INTO UsernameLedger ([Username], [UserId], [AssignedAtUtc], [RetiredAtUtc], [RetiredReason])
                    VALUES (@username, @userId, @at, @at, @reason);
                    """, cancellationToken, ("@username", previous), ("@userId", userId), ("@at", entry.FirstAt), ("@reason", UsernameRetiredReasons.BackfillPrevious)).ConfigureAwait(false);
                report.PreviousRecoveryAccessNamesRecorded++;
            }
            catch (SqlException ex) when (ex.Number is 2601 or 2627)
            {
                // Taken concurrently; the next start reports who holds it.
            }
        }
    }

    /// <summary>
    /// Parses <c>userId={id} previousUsername={name}</c>, optionally followed by the audit writer's
    /// <c>; Resource=…</c> suffix. Anything else is ignored rather than guessed at.
    /// </summary>
    internal static bool TryParseCanonicalization(string details, out string userId, out string previousUsername)
    {
        userId = "";
        previousUsername = "";
        var match = CanonicalizationDetails().Match(details);
        if (!match.Success)
            return false;

        var name = match.Groups["name"].Value;
        if (name.Length == 0 || !string.Equals(UsernamePolicy.Normalize(name), name, StringComparison.Ordinal))
            return false;

        userId = match.Groups["userId"].Value;
        previousUsername = name;
        return true;
    }

    [GeneratedRegex(@"^userId=(?<userId>[^\s;]+) previousUsername=(?<name>.*?)(?:; Resource=.*)?$", RegexOptions.Singleline | RegexOptions.CultureInvariant)]
    private static partial Regex CanonicalizationDetails();

    // ---------------------------------------------------------------------------------------------
    // 3. Everyone else: generated from directory snapshots.
    // ---------------------------------------------------------------------------------------------

    private static async Task GenerateRemainingUsernamesAsync(
        SqlConnection connection,
        UsernameBackfillReport report,
        ILogger logger,
        Func<string>? randomSuffix,
        CancellationToken cancellationToken)
    {
        var users = new List<(string UserId, string DisplayName)>();
        await using (var command = Command(connection, null, """
            SELECT u.[Id], u.[DisplayName]
            FROM Users u
            WHERE u.[Username] IS NULL
            ORDER BY (SELECT MIN(x.[LinkedAt]) FROM IdentityLinks x WHERE x.[UserId] = u.[Id]), u.[Id];
            """))
        await using (var reader = await command.ExecuteReaderAsync(cancellationToken).ConfigureAwait(false))
        {
            while (await reader.ReadAsync(cancellationToken).ConfigureAwait(false))
                users.Add((reader.GetString(0), reader.GetString(1)));
        }

        foreach (var (userId, displayName) in users)
        {
            var sources = await SourcesForAsync(connection, userId, displayName, cancellationToken).ConfigureAwait(false);
            var baseName = UsernamePolicy.GenerateBase(sources);

            var outcome = GenerationOutcome.Exhausted;
            string? assigned = null;
            foreach (var candidate in UsernamePolicy.CollisionCandidates(baseName, randomSuffix))
            {
                outcome = await TryAssignGeneratedAsync(connection, userId, candidate, cancellationToken).ConfigureAwait(false);
                if (outcome == GenerationOutcome.Taken)
                    continue;
                assigned = candidate;
                break;
            }

            switch (outcome)
            {
                case GenerationOutcome.Assigned:
                    report.Generated++;
                    if (!string.Equals(assigned, baseName, StringComparison.Ordinal))
                        report.GeneratedWithSuffix++;
                    logger.LogInformation("Generated username {Username} for user {UserId}.", assigned, userId);
                    break;
                case GenerationOutcome.AlreadyAssigned:
                    break;
                default:
                    throw new InvalidOperationException(
                        $"Cannot assign usernames: no free username could be generated for user {userId} from base '{baseName}'.");
            }
        }
    }

    private enum GenerationOutcome
    {
        Assigned,
        Taken,
        AlreadyAssigned,
        Exhausted,
    }

    private static async Task<GenerationOutcome> TryAssignGeneratedAsync(
        SqlConnection connection,
        string userId,
        string candidate,
        CancellationToken cancellationToken)
    {
        await using var transaction = (SqlTransaction)await connection.BeginTransactionAsync(cancellationToken).ConfigureAwait(false);
        var now = DateTimeOffset.UtcNow;
        try
        {
            await ExecuteAsync(connection, transaction, """
                INSERT INTO UsernameLedger ([Username], [UserId], [AssignedAtUtc], [RetiredAtUtc], [RetiredReason])
                VALUES (@username, @userId, @now, NULL, NULL);
                """, cancellationToken, ("@username", candidate), ("@userId", userId), ("@now", now)).ConfigureAwait(false);
        }
        catch (SqlException ex) when (ex.Number is 2601 or 2627)
        {
            await transaction.RollbackAsync(cancellationToken).ConfigureAwait(false);
            if (ex.Message.Contains("UX_UsernameLedger_Current_UserId", StringComparison.Ordinal))
            {
                // A concurrent start already gave this user a name; copy it if Users was not yet updated.
                await ExecuteAsync(connection, null, """
                    UPDATE u SET [Username] = l.[Username]
                    FROM Users u
                    INNER JOIN UsernameLedger l ON l.[UserId] = u.[Id] AND l.[RetiredAtUtc] IS NULL
                    WHERE u.[Id] = @userId AND u.[Username] IS NULL;
                    """, cancellationToken, ("@userId", userId)).ConfigureAwait(false);
                return GenerationOutcome.AlreadyAssigned;
            }

            return GenerationOutcome.Taken;
        }

        var updated = await ExecuteAsync(connection, transaction, """
            UPDATE Users SET [Username] = @username WHERE [Id] = @userId AND [Username] IS NULL;
            """, cancellationToken, ("@username", candidate), ("@userId", userId)).ConfigureAwait(false);
        if (updated == 0)
        {
            await transaction.RollbackAsync(cancellationToken).ConfigureAwait(false);
            return GenerationOutcome.AlreadyAssigned;
        }

        await ExecuteAsync(connection, transaction, """
            INSERT INTO AuditLogs ([At], [Actor], [Action], [Details], [Outcome])
            VALUES (@now, @actor, @action, @details, @outcome);
            """, cancellationToken,
            ("@now", now),
            ("@actor", SystemActor),
            ("@action", AssignedAuditAction),
            ("@details", $"userId={userId} username={candidate} source=generated"),
            ("@outcome", AuditOutcome)).ConfigureAwait(false);

        await transaction.CommitAsync(cancellationToken).ConfigureAwait(false);
        return GenerationOutcome.Assigned;
    }

    /// <summary>
    /// UPN and mail from the user's Entra link snapshots, then from the access request that provisioned
    /// the user. The display name, unless it is the default text given to configured bootstrap admins.
    /// </summary>
    private static async Task<UsernameGenerationSources> SourcesForAsync(
        SqlConnection connection,
        string userId,
        string displayName,
        CancellationToken cancellationToken)
    {
        string? upn = null;
        string? mail = null;

        await using (var command = Command(connection, null, """
            SELECT [UserPrincipalNameSnapshot], [MailSnapshot]
            FROM IdentityLinks
            WHERE [UserId] = @userId AND [Source] = @entra
            ORDER BY [LinkedAt], [Id];
            """, ("@userId", userId), ("@entra", EntraSource)))
        await using (var reader = await command.ExecuteReaderAsync(cancellationToken).ConfigureAwait(false))
        {
            while (await reader.ReadAsync(cancellationToken).ConfigureAwait(false))
            {
                upn ??= NullIfBlank(reader, 0);
                mail ??= NullIfBlank(reader, 1);
            }
        }

        if (upn is null || mail is null)
        {
            await using var command = Command(connection, null, """
                SELECT [UserPrincipalNameSnapshot], [MailSnapshot]
                FROM EntraAccessRequests
                WHERE [ProvisionedUserId] = @userId
                ORDER BY [RequestedAtUtc], [Id];
                """, ("@userId", userId));
            await using var reader = await command.ExecuteReaderAsync(cancellationToken).ConfigureAwait(false);
            while (await reader.ReadAsync(cancellationToken).ConfigureAwait(false))
            {
                upn ??= NullIfBlank(reader, 0);
                mail ??= NullIfBlank(reader, 1);
            }
        }

        var display = IsDefaultBootstrapDisplayName(displayName) ? null : displayName;
        return new UsernameGenerationSources(upn, mail, display);
    }

    internal static bool IsDefaultBootstrapDisplayName(string? displayName) =>
        displayName is not null
        && displayName.StartsWith(BootstrapDisplayNamePrefix, StringComparison.Ordinal)
        && displayName.EndsWith(')');

    // ---------------------------------------------------------------------------------------------
    // ADO helpers
    // ---------------------------------------------------------------------------------------------

    private static async Task<(string UserId, bool IsCurrent)?> LedgerOwnerAsync(
        SqlConnection connection,
        SqlTransaction? transaction,
        string username,
        CancellationToken cancellationToken)
    {
        await using var command = Command(connection, transaction, """
            SELECT [UserId], CASE WHEN [RetiredAtUtc] IS NULL THEN 1 ELSE 0 END
            FROM UsernameLedger WITH (UPDLOCK, HOLDLOCK)
            WHERE [Username] = @username;
            """, ("@username", username));
        await using var reader = await command.ExecuteReaderAsync(cancellationToken).ConfigureAwait(false);
        if (!await reader.ReadAsync(cancellationToken).ConfigureAwait(false))
            return null;
        return (reader.GetString(0), reader.GetInt32(1) == 1);
    }

    private static string? NullIfBlank(DbDataReader reader, int ordinal)
    {
        if (reader.IsDBNull(ordinal))
            return null;
        var value = reader.GetString(ordinal);
        return string.IsNullOrWhiteSpace(value) ? null : value;
    }

    private static SqlCommand Command(
        SqlConnection connection,
        SqlTransaction? transaction,
        string sql,
        params (string Name, object Value)[] parameters)
    {
        var command = connection.CreateCommand();
        command.Transaction = transaction;
        command.CommandText = sql;
        foreach (var (name, value) in parameters)
            command.Parameters.AddWithValue(name, value);
        return command;
    }

    private static async Task<int> ExecuteAsync(
        SqlConnection connection,
        SqlTransaction? transaction,
        string sql,
        CancellationToken cancellationToken,
        params (string Name, object Value)[] parameters)
    {
        await using var command = Command(connection, transaction, sql, parameters);
        return await command.ExecuteNonQueryAsync(cancellationToken).ConfigureAwait(false);
    }

    private static async Task<int> ScalarAsync(
        SqlConnection connection,
        SqlTransaction? transaction,
        string sql,
        CancellationToken cancellationToken,
        params (string Name, object Value)[] parameters)
    {
        await using var command = Command(connection, transaction, sql, parameters);
        return Convert.ToInt32(await command.ExecuteScalarAsync(cancellationToken).ConfigureAwait(false));
    }
}

/// <summary>Counts from one run of <see cref="UsernameBackfill"/>. A re-run reports zeros for work already done.</summary>
public sealed class UsernameBackfillReport
{
    /// <summary>Local sign-in names kept as usernames.</summary>
    public int LocalPreserved { get; set; }

    /// <summary>Of <see cref="LocalPreserved"/>, names that do not satisfy the current username policy.</summary>
    public int LocalGrandfathered { get; set; }

    public int Generated { get; set; }

    /// <summary>Of <see cref="Generated"/>, names that needed a collision suffix.</summary>
    public int GeneratedWithSuffix { get; set; }

    /// <summary>Users keeping a reserved name other than Recovery Access's own <c>breakglass</c>.</summary>
    public int ReservedNameHolders { get; set; }

    public int PreviousRecoveryAccessNamesRecorded { get; set; }

    /// <summary>Earlier Recovery Access names not recorded: ambiguous, owner missing, or held by another user.</summary>
    public int PreviousRecoveryAccessNamesSkipped { get; set; }
}
